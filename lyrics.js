function generateLyrics(lineCount, topic) {
  const n = Math.ceil(lineCount / 2);
  let pairs;
  const T = (topic || '').trim();
  if (T) {
    const cap = T.charAt(0).toUpperCase() + T.slice(1);
    const themed = shuffle(THEMED).map(p => p.map(l => l.replace('{T}', cap)));
    const plain = shuffle(COUPLETS);
    pairs = [];
    for (let i = 0; i < n; i++) pairs.push(i % 2 === 0 && themed.length ? themed.shift() : plain.shift());
  } else {
    pairs = shuffle(COUPLETS).slice(0, n);
  }
  return pairs.flat().slice(0, lineCount);
}

// Генерация текста через Claude API (ключ хранится только в браузере пользователя)
async function generateLyricsAI(prompt, lineCount, apiKey) {
  const { default: Anthropic } = await import('https://cdn.jsdelivr.net/npm/@anthropic-ai/sdk@0.65.0/+esm');
  const client = new Anthropic({ apiKey, dangerouslyAllowBrowser: true });
  const response = await client.beta.messages.create({
    model: 'claude-opus-5-5',
    max_tokens: 4000,
    output_config: { effort: 'low' },
    betas: ['server-side-fallback-2026-07-01'],
    fallbacks: 'default',
    system:
      'Ты пишешь оригинальные рэп-куплеты для читки под бит. Правила: ровно столько строк, сколько просят; ' +
      'одна строка = одна фраза на один такт (примерно 8–14 слогов); строки рифмуются попарно (AABB); ' +
      'пиши на языке запроса пользователя; без мата и оскорблений; без нумерации, заголовков, кавычек и пояснений — только строки текста, каждая с новой строки.',
    messages: [{ role: 'user', content: `Тема/промпт: ${prompt}\nКоличество строк: ${lineCount}` }],
  });
  if (response.stop_reason === 'refusal') throw new Error('Модель отказалась писать текст на эту тему');
  const text = response.content.filter(b => b.type === 'text').map(b => b.text).join('\n');
  const lines = text.split('\n').map(s => s.replace(/^\s*[\d\-–•.)]+\s*/, '').trim()).filter(Boolean);
  if (!lines.length) throw new Error('Пустой ответ');
  return lines.slice(0, lineCount);
}
